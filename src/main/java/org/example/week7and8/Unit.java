package org.example.week7and8;

class Unit{
    static double kmToMiles(double x){return x*0.621371;}
    static double milesToKm(double x){return x*1.60934;}
    static double mToFeet(double x){return x*3.28084;}
    static double feetToM(double x){return x*0.3048;}
    static double yardToFeet(double x){return x*3;}
    static double feetToYard(double x){return x*0.333333;}
    static double mToIn(double x){return x*39.3701;}
    static double inToM(double x){return x*0.0254;}
    static double inToCm(double x){return x*2.54;}
    static double fToC(double x){return (x-32)*5/9;}
    static double cToF(double x){return (x*9/5)+32;}
    static double poundToKg(double x){return x*0.453592;}
    static double kgToPound(double x){return x*2.20462;}
    static double gallonToL(double x){return x*3.78541;}
    static double lToGallon(double x){return x*0.264172;}
}
